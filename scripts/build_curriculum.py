"""Generate src/data/curriculum.json from the python-deepdive repository layout.

The site mirrors the course structure exactly: 4 parts, the same sections, the same
lectures (one lecture per notebook). Usage:

    python3 scripts/build_curriculum.py [path/to/python-deepdive]
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "python-deepdive"
OUT = ROOT / "src" / "data" / "curriculum.json"

PARTS = {
    1: ("Functional", "Variables and memory, numeric types, functions, closures, decorators, tuples, modules and packages."),
    2: ("Iteration, Generators", "Sequences, iterables and iterators, generators, iteration tools, context managers and generator-based coroutines."),
    3: ("Hash Maps", "Dictionaries, sets, hashing, serialization, and the specialized dictionaries in the standard library."),
    4: ("OOP", "Classes, properties, special methods, inheritance, slots, descriptors, enumerations, exceptions and metaprogramming."),
}

# Lecture entries (a notebook file or a lecture folder) whose name has no usable number
# prefix, keyed by (part, section, entry name without .ipynb) -> (lecture number, title).
ORDER_OVERRIDES = {
    (2, 9, "project_4_description"): (1, "Project Description"),
    (2, 9, "project_4_goal_1"): (2, "Project Solution - Goal 1"),
    (2, 9, "project_4_goal_2"): (3, "Project Solution - Goal 2"),
    (2, 9, "project_4_goal_3"): (4, "Project Solution - Goal 3"),
    (2, 9, "project_4_goal_4"): (5, "Project Solution - Goal 4"),
    (3, 10, "Exercise 1 - Solution"): (2, "Exercise 1 - Solution"),
    (3, 10, "Exercise 2 - Solution"): (3, "Exercise 2 - Solution"),
    (3, 10, "03 - Exercise 3 - Solution"): (4, "Exercise 3 - Solution"),
    (4, 7, "Project 3 - Description"): (1, "Project 3 - Description"),
    (4, 7, "Project 3 - Solution - Approach"): (2, "Project 3 - Solution - Approach"),
    (4, 11, "Solution"): (1, "Project 5 - Solution"),
    (4, 13, "Project 6 - Exceptions"): (1, "Project 6 - Description"),
    (4, 13, "Project 6 - Exceptions - Solution"): (2, "Project 6 - Solution"),
    (4, 5, "Project 2 - Solution"): (1, "Project 2 - Solution"),
}

# Folders inside a section that hold project code rather than a lecture.
NOT_LECTURES = {"app", "tests", ".ipynb_checkpoints", "__pycache__"}

# Lectures that exist in the original course (we have their captions) but have no notebook.
# They're inserted before the named lecture; the whole section is then renumbered 1..n so the
# order matches the course.
EXTRA_LECTURES = {
    (1, 2): [
        {"title": "The Python Type Hierarchy", "before": "Multi-Line Statements and Strings",
         "source": "Part 1/Captioning/section02/the-python-type-hierarchyautogenerated.vtt"},
        {"title": "Variable Names", "before": "Conditionals",
         "source": "Part 1/Captioning/section02/variable-namesautogenerated.vtt"},
    ],
}

TITLE_FIXES = {"Python. Updates": "Python Updates", "DefaultValues": "Default Values", "command line arguments": "Command Line Arguments"}


def slugify(text: str) -> str:
    text = text.lower().replace("_", "-")
    text = re.sub(r"[^a-z0-9]+", "-", text)
    return text.strip("-")


def clean_title(text: str) -> str:
    for old, new in TITLE_FIXES.items():
        text = text.replace(old, new)
    text = text.replace("3.8_3.7", "3.8 / 3.7").replace("2b_c", "2b/c")
    return re.sub(r"\s+", " ", text).strip()


def section_kind(title: str) -> str:
    if title.startswith("Project"):
        return "project"
    if title.startswith("Coding Exercises"):
        return "exercises"
    return "lessons"


def main() -> None:
    parts = []
    for part_num, (subtitle, blurb) in PARTS.items():
        part_dir = REPO / f"Part {part_num}"
        sections = []
        for sec_dir in sorted(p for p in part_dir.iterdir() if p.is_dir()):
            m = re.match(r"Section (\d+) - (.+)", sec_dir.name)
            if not m:
                continue  # e.g. the Captioning folder
            sec_num, sec_title = int(m.group(1)), clean_title(m.group(2))
            lectures = []
            for entry in sec_dir.iterdir():
                if entry.is_dir():
                    if entry.name in NOT_LECTURES:
                        continue
                    name = entry.name
                elif entry.suffix == ".ipynb":
                    name = entry.stem
                else:
                    continue
                key = (part_num, sec_num, name)
                lm = re.match(r"(\d+)\s*-\s*(.+)", name)
                if key in ORDER_OVERRIDES:
                    num, title = ORDER_OVERRIDES[key]
                elif lm:
                    num, title = int(lm.group(1)), lm.group(2)
                else:
                    raise SystemExit(f"No lecture number for {entry}; add it to ORDER_OVERRIDES")
                if "_" in title and " " not in title:  # folder names like structuring_package_imports
                    title = title.replace("_", " ")
                if title.islower():
                    title = title.title()
                title = clean_title(title)
                lectures.append({
                    "num": num,
                    "slug": f"{num:02d}-{slugify(title)}",
                    "title": title,
                    "source": str(entry.relative_to(REPO)),
                })
            lectures.sort(key=lambda l: l["num"])
            for extra in EXTRA_LECTURES.get((part_num, sec_num), []):
                idx = next(i for i, l in enumerate(lectures) if l["title"] == extra["before"])
                lectures.insert(idx, {"num": 0, "title": extra["title"], "source": extra["source"]})
            if (part_num, sec_num) in EXTRA_LECTURES:
                for i, lec in enumerate(lectures, start=1):
                    lec["num"] = i
                    lec["slug"] = f"{i:02d}-{slugify(lec['title'])}"
            nums = [l["num"] for l in lectures]
            if len(nums) != len(set(nums)):
                raise SystemExit(f"Duplicate lecture numbers in {sec_dir}: {nums}")
            sections.append({
                "num": sec_num,
                "slug": f"section-{sec_num:02d}",
                "title": sec_title,
                "kind": section_kind(sec_title),
                "lectures": lectures,
            })
        sections.sort(key=lambda s: s["num"])
        parts.append({
            "num": part_num,
            "slug": f"part-{part_num}",
            "title": f"Part {part_num}",
            "subtitle": subtitle,
            "blurb": blurb,
            "sections": sections,
        })

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"parts": parts}, indent=2) + "\n")
    n_sec = sum(len(p["sections"]) for p in parts)
    n_lec = sum(len(s["lectures"]) for p in parts for s in p["sections"])
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(parts)} parts, {n_sec} sections, {n_lec} lectures")


if __name__ == "__main__":
    main()
